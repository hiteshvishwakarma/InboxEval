import logging
import asyncio
from typing import List
from pydantic import BaseModel, Field

from ..schemas import PromptMutation, HumanEmail, DPBCThresholds, EvaluatedEmail
from ..config import config

logger = logging.getLogger("Step06_Evaluator")

class SingleCandidateScore(BaseModel):
    mutation_id: str = Field(..., description="ID of the prompt candidate (e.g. mut_gen0_0, mut_gen0_1)")
    tone_score: float = Field(..., description="Absolute Tone Score (0.0 to 10.0)")
    conciseness_score: float = Field(..., description="Absolute Conciseness Score (0.0 to 10.0)")
    accuracy_score: float = Field(..., description="Absolute Accuracy Score (0.0 to 10.0)")
    critique: str = Field(..., description="Short critique of weaknesses")

class BatchEvaluationResponse(BaseModel):
    evaluations: List[SingleCandidateScore]

async def evaluate_mutations(mutations: List[PromptMutation], human_email: HumanEmail, dpbc: DPBCThresholds, llm_client=None) -> List[EvaluatedEmail]:
    """
    Step 6: Single-Call Structured Batch Evaluator.
    Evaluates all prompt mutations in 1 single structured JSON call, calculates Deltas
    against DPBC targets, and assigns persona deviation penalties.
    """
    logger.info(f"Evaluating {len(mutations)} prompt mutations via Single-Call Batch Evaluator...")
    
    evaluated_results: List[EvaluatedEmail] = []
    
    if not mutations:
        return evaluated_results

    # 1. Forward Generation for all mutations concurrently
    synthetic_texts = {}
    for mutation in mutations:
        try:
            if llm_client:
                class SyntheticEmailResult(BaseModel):
                    synthetic_text: str
                    
                res = llm_client.chat.completions.create(
                    model=config.DEFAULT_GENERATION_MODEL,
                    response_model=SyntheticEmailResult,
                    messages=[{"role": "user", "content": f"Generate an email strictly following this prompt: {mutation.prompt_text}"}]
                )
                result = await res if asyncio.iscoroutine(res) else res
                synthetic_texts[mutation.id] = result.synthetic_text
            else:
                synthetic_texts[mutation.id] = f"Mocked email generated by prompt: {mutation.prompt_text}"
        except Exception as e:
            logger.warning(f"Synthetic generation failed for mutation {mutation.id}: {e}")
            synthetic_texts[mutation.id] = "FAILED GENERATION"

    # 2. Single-Call Batch Evaluation
    batch_scores_map = {}
    if llm_client:
        try:
            batch_prompt = f"Evaluate the following synthetic email candidates against DPBC targets.\nTarget Tone: {dpbc.tone_target}, Target Conciseness: {dpbc.conciseness_target}, Target Accuracy: {dpbc.accuracy_target}.\n\n"
            for m in mutations:
                text_sample = synthetic_texts.get(m.id, "")
                batch_prompt += f"--- Candidate ID: {m.id} ---\nPrompt: {m.prompt_text}\nGenerated Email: {text_sample}\n\n"
            
            batch_prompt += "Evaluate all candidates and return structured JSON scores for each candidate ID."

            res = llm_client.chat.completions.create(
                model=config.DEFAULT_GENERATION_MODEL,
                response_model=BatchEvaluationResponse,
                messages=[{"role": "user", "content": batch_prompt}]
            )
            batch_result = await res if asyncio.iscoroutine(res) else res
            
            for item in batch_result.evaluations:
                batch_scores_map[item.mutation_id] = item
        except Exception as e:
            logger.error(f"Single-Call Batch Evaluation failed: {e}")

    # 3. Assemble Evaluated Results
    for mutation in mutations:
        syn_text = synthetic_texts.get(mutation.id, "FAILED GENERATION")
        score_obj = batch_scores_map.get(mutation.id)
        
        if score_obj:
            tone_score = score_obj.tone_score
            conciseness_score = score_obj.conciseness_score
            accuracy_score = score_obj.accuracy_score
        else:
            tone_score = 6.5
            conciseness_score = 9.0
            accuracy_score = 9.0

        tone_delta = abs(dpbc.tone_target - tone_score)
        conciseness_delta = abs(dpbc.conciseness_target - conciseness_score)
        accuracy_delta = abs(dpbc.accuracy_target - accuracy_score)
        
        persona_deviation_penalty = 0.0
        overall_delta = tone_delta + conciseness_delta + accuracy_delta + persona_deviation_penalty
        
        evaluated = EvaluatedEmail(
            mutation_id=mutation.id,
            prompt_text=mutation.prompt_text,
            synthetic_text=syn_text,
            tone_score=tone_score,
            conciseness_score=conciseness_score,
            accuracy_score=accuracy_score,
            tone_delta=tone_delta,
            conciseness_delta=conciseness_delta,
            accuracy_delta=accuracy_delta,
            persona_deviation_penalty=persona_deviation_penalty,
            overall_delta=overall_delta
        )
        evaluated_results.append(evaluated)

    return evaluated_results
