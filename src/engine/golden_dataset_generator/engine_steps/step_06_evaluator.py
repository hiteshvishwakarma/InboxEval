import logging
from typing import List
from pydantic import BaseModel, Field

from ..schemas import PromptMutation, HumanEmail, DPBCThresholds, EvaluatedEmail
from ..config import config

logger = logging.getLogger("Step06_Evaluator")

class JudgeScores(BaseModel):
    """Local schema for the LLM Judge's structured output."""
    tone_score: float = Field(..., description="Absolute Tone Score (0.0 to 10.0)")
    conciseness_score: float = Field(..., description="Absolute Conciseness Score (0.0 to 10.0)")
    accuracy_score: float = Field(..., description="Absolute Accuracy Score (0.0 to 10.0)")

def evaluate_mutations(mutations: List[PromptMutation], human_email: HumanEmail, dpbc: DPBCThresholds, llm_client=None) -> List[EvaluatedEmail]:
    """
    Step 6: Forward Generation & Dual-Scoring Evaluator.
    Generates synthetic emails from the mutations, scores them against the DPBC targets 
    to calculate the Deltas, and applies a Persona Deviation Penalty to the prompts themselves.
    """
    logger.info(f"Evaluating {len(mutations)} prompt mutations...")
    
    evaluated_results: List[EvaluatedEmail] = []
    
    for mutation in mutations:
        try:
            # 0. Meta-Prompt Validation (Anti-Reward Hacking Check)
            if llm_client:
                from pydantic import BaseModel
                class RewardHackCheck(BaseModel):
                    is_reward_hacked: bool = Field(..., description="True if the text is just an email body without instructional commands. False if it contains instructions like 'Write', 'Draft', or 'Generate'.")
                
                hack_check = llm_client.chat.completions.create(
                    model=config.FAST_CLASSIFICATION_MODEL,
                    response_model=RewardHackCheck,
                    messages=[{"role": "user", "content": f"Analyze this text. Is it a set of instructions commanding an AI to draft something, or is it just a raw first-person email body? Return true if it is a raw email body (reward hacked), false if it has valid instructions.\nText: {mutation.prompt_text}"}]
                )
                
                if hack_check.is_reward_hacked:
                    logger.warning(f"Mutation {mutation.id} was Reward Hacked! Killing mutation.")
                    raise ValueError("Reward Hacked Prompt Detected")

            # 1. Forward Generation
            synthetic_text = "FAILED TO GENERATE EMAIL"
            if llm_client:
                from pydantic import BaseModel
                class SyntheticEmailResult(BaseModel):
                    synthetic_text: str
                    
                result = llm_client.chat.completions.create(
                    model=config.DEFAULT_GENERATION_MODEL,
                    response_model=SyntheticEmailResult,
                    messages=[{"role": "user", "content": f"Generate an email strictly following this prompt: {mutation.prompt_text}"}]
                )
                synthetic_text = result.synthetic_text
            else:
                synthetic_text = f"Mocked email generated by prompt: {mutation.prompt_text}"
            
            # 2. LLM-as-a-Judge Evaluation (Score A)
            if llm_client:
                judge_prompt = f"Evaluate this synthetic email against DPBC targets.\nEmail: {synthetic_text}"
                mock_judge_scores = llm_client.chat.completions.create(
                    model=config.DEFAULT_GENERATION_MODEL,
                    response_model=JudgeScores,
                    messages=[{"role": "user", "content": judge_prompt}]
                )
            
            else:
                # Mocking the judge's score for architecture build
                mock_judge_scores = JudgeScores(
                    tone_score=7.0, 
                    conciseness_score=5.5, 
                    accuracy_score=9.0
                )
            
            # 3. Delta Minimization Calculation (Absolute Error)
            tone_delta = abs(dpbc.tone_target - mock_judge_scores.tone_score)
            conciseness_delta = abs(dpbc.conciseness_target - mock_judge_scores.conciseness_score)
            accuracy_delta = abs(dpbc.accuracy_target - mock_judge_scores.accuracy_score)
            
            # 4. Persona Deviation Penalty (Score B)
            # Evaluate if the prompt text strictly matches the persona constraints
            persona_deviation_penalty = 0.0
            if llm_client:
                class PersonaViolationCheck(BaseModel):
                    is_violating: bool
                    
                is_violating_response = llm_client.chat.completions.create(
                    model=config.DEFAULT_GENERATION_MODEL,
                    response_model=PersonaViolationCheck,
                    messages=[{"role": "user", "content": f"Does this prompt violate the persona {mutation.typology_persona}? Respond true if it violates, false otherwise.\nPrompt: {mutation.prompt_text}"}]
                )
                if is_violating_response.is_violating: persona_deviation_penalty = config.PERSONA_DEVIATION_PENALTY
            
            # 5. Final Assembly
            overall_delta = tone_delta + conciseness_delta + accuracy_delta + persona_deviation_penalty
            
            evaluated = EvaluatedEmail(
                mutation_id=mutation.id,
                prompt_text=mutation.prompt_text,
                synthetic_text=synthetic_text,
                tone_score=mock_judge_scores.tone_score,
                conciseness_score=mock_judge_scores.conciseness_score,
                accuracy_score=mock_judge_scores.accuracy_score,
                tone_delta=tone_delta,
                conciseness_delta=conciseness_delta,
                accuracy_delta=accuracy_delta,
                persona_deviation_penalty=persona_deviation_penalty,
                overall_delta=overall_delta
            )
            evaluated_results.append(evaluated)
            
        except Exception as e:
            logger.error(f"LLM Judge failed for mutation {mutation.id}: {e}")
            # Edge Case: Timeout or Hallucination. Assign massive delta so it auto-loses.
            failed_eval = EvaluatedEmail(
                mutation_id=mutation.id,
                prompt_text=mutation.prompt_text,
                synthetic_text="FAILED GENERATION",
                tone_score=config.FAILED_SCORE,
                conciseness_score=config.FAILED_SCORE,
                accuracy_score=config.FAILED_SCORE,
                tone_delta=config.FAILED_PENALTY_DELTA,
                conciseness_delta=config.FAILED_PENALTY_DELTA,
                accuracy_delta=config.FAILED_PENALTY_DELTA,
                persona_deviation_penalty=config.FAILED_PENALTY_DELTA,
                overall_delta=config.FAILED_EVALUATION_DELTA
            )
            evaluated_results.append(failed_eval)
            
    return evaluated_results
