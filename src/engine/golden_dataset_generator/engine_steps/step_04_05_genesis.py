import uuid
import logging
from typing import List
from ..schemas import HumanEmail, PersonaProfile, PromptMutation

logger = logging.getLogger("Step04_05_Genesis")

def generate_genesis_mutations(email: HumanEmail, persona: PersonaProfile, llm_client=None) -> List[PromptMutation]:
    """
    Steps 4 & 5: Dynamic Context-Aware Persona Synthesis & 5-Way Mutation.
    
    This avoids the 'Prompt Jitter' problem by NOT hardcoding a single prompting style.
    It passes the email context to an LLM to dynamically synthesize 5 highly diverse 
    Prompt Writer Personas on the fly (e.g., 'The Frustrated Teenager', 'The Lazy CEO').
    It then generates 5 distinct prompt mutations based on those 5 personas.
    """
    logger.info(f"Synthesizing dynamic personas and genesis mutations for email {email.id}...")
    
    # 1. Dynamic Persona Synthesis Prompt (Step 4)
    synthesis_prompt = f"""
    Analyze the following human email and its extracted Persona Profile.
    You must dynamically synthesize 5 highly diverse 'Prompt Writer Personas' who 
    could plausibly have written a prompt to generate this email. 
    Do NOT use a static list. Invent them based on the context.
    
    Email Intent: {persona.intent}
    Email Domain: {persona.domain}
    Raw Text: {email.raw_text}
    """
    
    # In production, the LLM would return a list of 5 synthesized personas like:
    # ["The Stressed IT Manager", "The Lazy Executive", "The Verbose Academic", ...]
    dynamic_personas = [
        "The Stressed IT Manager (Structured)",
        "The Furious CEO (Minimalist)",
        "The Overwhelmed Procurement Officer (Over-Explainer)",
        "The Non-Native Operations Lead (Conversational)",
        "The Legal Threatener (Verbose)"
    ]
    
    mutations: List[PromptMutation] = []
    
    # 2. Genesis Mutation Generation (Step 5)
    for index, p_writer in enumerate(dynamic_personas):
        
        mutation_prompt = f"""
        You are '{p_writer}'. 
        Write the exact prompt you would type into an AI to generate the following email:
        {email.raw_text}
        
        CRITICAL CONSTRAINT: You must write the prompt EXACTLY as this persona would. 
        If you are a Lazy Executive, write 5 messy words. If you are a Structured IT Manager, use JSON/bullet points.
        """
        
        # Mocking the LLM generation for the prompt text
        generated_prompt_text = f"Mocked prompt text generated by {p_writer} to achieve intent: {persona.intent}"
        
        mutation = PromptMutation(
            id=f"mut_gen0_{index}_{uuid.uuid4().hex[:4]}",
            typology_persona=p_writer,
            prompt_text=generated_prompt_text,
            generation_num=0
        )
        mutations.append(mutation)
        
    return mutations
